import assert from 'node:assert/strict';
import {readFile, mkdir, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {chromium} from 'playwright';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const base = process.env.ANANTAM_BASE_URL || 'http://127.0.0.1:8917/';
const out = resolve(process.env.ANANTAM_QA_DIR || 'work/browser');
const axe = await readFile(require.resolve('axe-core/axe.min.js'), 'utf8');
const browser = await chromium.launch();
const checks = [], audits = [], errors = [];
const check = (name, ok) => {assert.ok(ok, name); checks.push(name);};
await mkdir(out, {recursive: true});
try {
  const page = await browser.newPage();
  page.on('pageerror', e => errors.push(e.message));
  for (const width of [320, 390, 768, 1440, 1920]) {
    await page.setViewportSize({width, height: width < 700 ? 844 : 900});
    await page.goto(base);
    await page.locator('.evidence-result').first().waitFor();
    await page.evaluate(() => document.fonts.ready);
    await page.waitForFunction(() => !window.gsap?.isTweening('.company-intro, .hero-art'));
    check(`${width}px: no horizontal overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    check(`${width}px: company positioning`, await page.getByText('We’re Anantam, an experimental AI company.', {exact:false}).isVisible());
    check(`${width}px: one contribution and three sections`, await page.locator('main > section').count() === 3 && await page.locator('main article').count() === 1);
    await page.evaluate(axe);
    const violations = await page.evaluate(async () => (await axe.run(document, {runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}})).violations.map(v => ({id:v.id,nodes:v.nodes.map(n=>n.target)})));
    audits.push({width,theme:'light',violations});
  }
  check('Real leading model and score', (await page.locator('.evidence-result').first().innerText()).includes('typesafe/jev-1.14') && (await page.locator('.evidence-result').first().innerText()).includes('51.70'));
  check('Company homepage does not show benchmark scope banner', await page.locator('.status-banner').count() === 0);
  await page.getByRole('link', {name:'Explore the benchmark',exact:true}).click();
  await page.getByRole('tab', {name:'Rankings',exact:true}).waitFor();
  check('Contribution opens full benchmark workspace', page.url().endsWith('/benchmark.html'));
  await page.getByRole('link', {name:'Anantam home',exact:true}).click();
  await page.locator('.evidence-result').first().waitFor();
  check('Brand returns to company homepage', await page.title() === 'Anantam | An experimental AI company');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('.ember-contribution').scrollIntoViewIfNeeded();
  await page.locator('.ember-contribution').hover({position:{x:40,y:40}});
  await page.waitForTimeout(500);
  check('Product card responds with depth', await page.locator('.ember-evidence').evaluate(el => getComputedStyle(el).transform !== 'none'));
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForTimeout(100);
  check('Reduced motion resets product depth', await page.locator('.ember-evidence').evaluate(el => getComputedStyle(el).transform === 'none'));
  await page.getByRole('button', {name:'Switch to dark theme',exact:true}).click();
  await page.evaluate(axe);
  audits.push({width:1440,theme:'dark',violations:await page.evaluate(async()=>(await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}})).violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})))});
  await page.screenshot({path:resolve(out,'company-dark.png'),fullPage:true});
  await page.getByRole('button', {name:'Switch to light theme',exact:true}).click();
  await page.evaluate(() => scrollTo(0,0));
  await page.screenshot({path:resolve(out,'company-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:resolve(out,'company-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'Menu',exact:true}).click();
  await page.getByRole('link',{name:'Our work',exact:true}).click();
  check('Mobile contribution anchor closes menu',await page.locator('.nav-toggle').getAttribute('aria-expanded') === 'false' && page.url().endsWith('#contributions'));
  const offline = await browser.newPage();
  await offline.route('**/data/results.js',route => route.abort());
  await offline.goto(base);
  await offline.getByText('The preview is unavailable.',{exact:false}).waitFor();
  check('Data failure preserves company and benchmark action',await offline.locator('h1').isVisible() && await offline.getByRole('link',{name:'Explore the benchmark',exact:true}).isVisible());
  const noMotionLibrary = await browser.newPage();
  await noMotionLibrary.route('**/gsap.min.js',route=>route.abort());
  await noMotionLibrary.goto(base);
  await noMotionLibrary.locator('.evidence-result').first().waitFor();
  check('Unavailable animation library preserves page',await noMotionLibrary.locator('h1').isVisible());
  const nojs = await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const staticPage = await nojs.newPage(); await staticPage.goto(base);
  check('All company content and contribution survive without JavaScript',await staticPage.locator('main > section').count() === 3 && await staticPage.getByRole('link',{name:'Explore the benchmark',exact:true}).isVisible());
  await nojs.close();
  const finite = await browser.newPage(); await finite.goto(base);
  await finite.waitForFunction(()=>document.querySelector('.cosmos-emblem')?.dataset.motion==='complete');
  const first = await finite.locator('canvas').evaluate(el=>el.toDataURL());
  await finite.waitForTimeout(200);
  check('Homepage flight stops after its finite introduction', first === await finite.locator('canvas').evaluate(el=>el.toDataURL()));
  check('No unexpected JavaScript errors',errors.length===0);
  check('Company accessibility scans have no violations',audits.every(a=>a.violations.length===0));
} finally {
  await writeFile(resolve(out,'company-report.json'),JSON.stringify({checks,audits,errors},null,2));
  await browser.close();
}
console.log(`${checks.length} company checks passed; ${audits.length} accessibility scans.`);
